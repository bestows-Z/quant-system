package logic

import (
	"context"

	"quant-system/backend-go/apps/paper-rpc/internal/svc"
	"quant-system/backend-go/apps/paper-rpc/paper"

	"github.com/zeromicro/go-zero/core/logx"
)

type GetAccountLogic struct {
	ctx    context.Context
	svcCtx *svc.ServiceContext
	logx.Logger
}

func NewGetAccountLogic(ctx context.Context, svcCtx *svc.ServiceContext) *GetAccountLogic {
	return &GetAccountLogic{
		ctx:    ctx,
		svcCtx: svcCtx,
		Logger: logx.WithContext(ctx),
	}
}

func (l *GetAccountLogic) GetAccount(in *paper.GetAccountReq) (*paper.GetAccountResp, error) {
	account, err := l.svcCtx.Trading.GetAccount(l.ctx, in.GetUserId(), in.GetAccountId())
	if err != nil {
		return nil, err
	}
	return &paper.GetAccountResp{Account: account}, nil
}
