CREATE TABLE IF NOT EXISTS rag_vector_cleanup_tasks (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  operation VARCHAR(32) NOT NULL,
  collection_name VARCHAR(255) NOT NULL,
  point_ids_json JSON DEFAULT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
  retry_count INT NOT NULL DEFAULT 0,
  last_error VARCHAR(1000) DEFAULT NULL,
  next_retry_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_cleanup_status_retry (status, next_retry_at, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='MySQL软删除后Qdrant清理重试任务';
