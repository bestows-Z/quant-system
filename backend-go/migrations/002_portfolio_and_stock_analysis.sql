CREATE TABLE IF NOT EXISTS real_portfolios (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(80) NOT NULL,
  description VARCHAR(500) NOT NULL DEFAULT '',
  base_currency VARCHAR(8) NOT NULL DEFAULT 'CNY',
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) DEFAULT NULL,
  active_name VARCHAR(80) GENERATED ALWAYS AS (CASE WHEN deleted_at IS NULL THEN name ELSE NULL END) STORED,
  PRIMARY KEY (id),
  UNIQUE KEY uk_real_portfolios_user_name (user_id, active_name),
  KEY idx_real_portfolios_user_status (user_id, status),
  KEY idx_real_portfolios_deleted_at (deleted_at),
  CONSTRAINT fk_real_portfolios_user FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS real_positions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  portfolio_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  symbol VARCHAR(16) NOT NULL,
  name VARCHAR(80) NOT NULL DEFAULT '',
  quantity BIGINT NOT NULL,
  available_quantity BIGINT NOT NULL DEFAULT 0,
  avg_cost DECIMAL(20,6) NOT NULL,
  opened_on DATE DEFAULT NULL,
  note VARCHAR(500) NOT NULL DEFAULT '',
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) DEFAULT NULL,
  active_symbol VARCHAR(16) GENERATED ALWAYS AS (CASE WHEN deleted_at IS NULL THEN symbol ELSE NULL END) STORED,
  PRIMARY KEY (id),
  UNIQUE KEY uk_real_positions_portfolio_symbol (portfolio_id, active_symbol),
  KEY idx_real_positions_user_portfolio (user_id, portfolio_id),
  KEY idx_real_positions_symbol (symbol),
  KEY idx_real_positions_deleted_at (deleted_at),
  CONSTRAINT fk_real_positions_portfolio FOREIGN KEY (portfolio_id) REFERENCES real_portfolios(id),
  CONSTRAINT fk_real_positions_user FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS position_import_tasks (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  portfolio_id BIGINT UNSIGNED NOT NULL,
  file_name VARCHAR(255) NOT NULL,
  file_hash CHAR(64) NOT NULL,
  idempotency_key VARCHAR(80) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PREVIEWED',
  total_rows INT UNSIGNED NOT NULL DEFAULT 0,
  valid_rows INT UNSIGNED NOT NULL DEFAULT 0,
  invalid_rows INT UNSIGNED NOT NULL DEFAULT 0,
  preview_json JSON NOT NULL,
  error_json JSON DEFAULT NULL,
  confirmed_at DATETIME(3) DEFAULT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_position_import_idempotency (user_id, portfolio_id, idempotency_key),
  KEY idx_position_import_hash (user_id, portfolio_id, file_hash),
  KEY idx_position_import_status (status, created_at),
  CONSTRAINT fk_position_import_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_position_import_portfolio FOREIGN KEY (portfolio_id) REFERENCES real_portfolios(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS portfolio_snapshots (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  portfolio_id BIGINT UNSIGNED NOT NULL,
  snapshot_time DATETIME(3) NOT NULL,
  market_value DECIMAL(24,6) NOT NULL DEFAULT 0,
  cost_value DECIMAL(24,6) NOT NULL DEFAULT 0,
  total_profit DECIMAL(24,6) NOT NULL DEFAULT 0,
  total_profit_rate DECIMAL(16,8) NOT NULL DEFAULT 0,
  data_source VARCHAR(40) NOT NULL DEFAULT '',
  data_mode VARCHAR(20) NOT NULL DEFAULT '',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_portfolio_snapshots_time (portfolio_id, snapshot_time),
  KEY idx_portfolio_snapshots_user_time (user_id, snapshot_time),
  CONSTRAINT fk_portfolio_snapshots_portfolio FOREIGN KEY (portfolio_id) REFERENCES real_portfolios(id),
  CONSTRAINT fk_portfolio_snapshots_user FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS portfolio_analysis_records (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  portfolio_id BIGINT UNSIGNED NOT NULL,
  analysis_version VARCHAR(32) NOT NULL,
  quote_time DATETIME(3) DEFAULT NULL,
  market_value DECIMAL(24,6) NOT NULL DEFAULT 0,
  total_profit DECIMAL(24,6) NOT NULL DEFAULT 0,
  total_profit_rate DECIMAL(16,8) NOT NULL DEFAULT 0,
  concentration DECIMAL(16,8) NOT NULL DEFAULT 0,
  volatility DECIMAL(16,8) NOT NULL DEFAULT 0,
  max_drawdown DECIMAL(16,8) NOT NULL DEFAULT 0,
  risk_level VARCHAR(16) NOT NULL DEFAULT 'LOW',
  coverage_rate DECIMAL(16,8) NOT NULL DEFAULT 0,
  industry_exposure_json JSON NOT NULL,
  position_analysis_json JSON NOT NULL,
  warnings_json JSON NOT NULL,
  data_source VARCHAR(40) NOT NULL DEFAULT '',
  data_mode VARCHAR(20) NOT NULL DEFAULT '',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_portfolio_analysis_portfolio_time (portfolio_id, created_at),
  KEY idx_portfolio_analysis_user_time (user_id, created_at),
  CONSTRAINT fk_portfolio_analysis_portfolio FOREIGN KEY (portfolio_id) REFERENCES real_portfolios(id),
  CONSTRAINT fk_portfolio_analysis_user FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS support_resistance_levels (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  symbol VARCHAR(16) NOT NULL,
  period VARCHAR(16) NOT NULL DEFAULT 'daily',
  quote_time DATETIME(3) NOT NULL,
  support_price DECIMAL(20,6) NOT NULL,
  pivot_price DECIMAL(20,6) NOT NULL,
  resistance_price DECIMAL(20,6) NOT NULL,
  support_strength DECIMAL(16,8) NOT NULL DEFAULT 0,
  resistance_strength DECIMAL(16,8) NOT NULL DEFAULT 0,
  method_json JSON NOT NULL,
  algorithm_version VARCHAR(32) NOT NULL,
  data_source VARCHAR(40) NOT NULL DEFAULT '',
  valid_until DATETIME(3) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_support_resistance_version (symbol, period, quote_time, algorithm_version),
  KEY idx_support_resistance_latest (symbol, period, valid_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
